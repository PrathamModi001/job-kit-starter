import json

with open("job-kit-starter/output/base_resume_b64.txt", "r", encoding="utf-8") as f:
    b64 = f.read().strip()

with open("job-kit-starter/drafts_payload.json", "r", encoding="utf-8") as f:
    targets = json.load(f)

js_lines = [
    "async (page) => {",
    "  const b64 = " + json.dumps(b64) + ";",
    "  const targets = " + json.dumps(targets) + ";",
    "  const results = [];",
    "",
    "  if (!page.url().includes('mail.google.com')) {",
    "    await page.goto('https://mail.google.com/mail/u/0/#inbox', { waitUntil: 'networkidle', timeout: 30000 });",
    "  }",
    "",
    "  for (let i = 0; i < targets.length; i++) {",
    "    const item = targets[i];",
    "    console.log(`[Draft ${i+1}/${targets.length}] Preparing: ${item.company} (${item.email})`);",
    "",
    "    const opened = await page.evaluate(() => {",
    "      const btns = Array.from(document.querySelectorAll(\"div[role='button'], div.T-I\"));",
    "      const btn = btns.find(b => b.innerText && b.innerText.includes('Compose'));",
    "      if (btn) {",
    "        btn.click();",
    "        return true;",
    "      }",
    "      return false;",
    "    });",
    "",
    "    if (!opened) {",
    "      results.push({ company: item.company, email: item.email, status: 'FAILED_NO_COMPOSE' });",
    "      continue;",
    "    }",
    "    await page.waitForTimeout(2000);",
    "",
    "    try {",
    "      const toInput = page.locator(\"input[aria-label*='To'], input[peoplekit-id], input.agP\").first();",
    "      await toInput.fill(item.email);",
    "      await page.keyboard.press('Enter');",
    "      await page.waitForTimeout(500);",
    "    } catch (e) {",
    "      console.log('Error setting To:', e.message);",
    "    }",
    "",
    "    try {",
    "      const subjectInput = page.locator(\"input[name='subjectbox']\");",
    "      await subjectInput.fill(item.subject);",
    "      await page.waitForTimeout(500);",
    "    } catch (e) {",
    "      console.log('Error setting Subject:', e.message);",
    "    }",
    "",
    "    try {",
    "      const bodyInput = page.locator(\"div[role='textbox'][aria-label*='Message Body']\");",
    "      await bodyInput.fill(item.body);",
    "      await page.waitForTimeout(500);",
    "    } catch (e) {",
    "      console.log('Error setting Body:', e.message);",
    "    }",
    "",
    "    try {",
    "      await page.evaluate((b64) => {",
    "        const input = document.querySelector(\"input[type='file'][name='Filedata']\");",
    "        if (!input) return false;",
    "        const binary = atob(b64);",
    "        const bytes = new Uint8Array(binary.length);",
    "        for (let j = 0; j < binary.length; j++) bytes[j] = binary.charCodeAt(j);",
    "        const blob = new Blob([bytes], { type: 'application/pdf' });",
    "        const file = new File([blob], 'Pratham_Modi_Resume.pdf', { type: 'application/pdf', lastModified: Date.now() });",
    "",
    "        const dt = new DataTransfer();",
    "        dt.items.add(file);",
    "        input.files = dt.files;",
    "        input.dispatchEvent(new Event('change', { bubbles: true }));",
    "        input.dispatchEvent(new Event('input', { bubbles: true }));",
    "        return true;",
    "      }, b64);",
    "    } catch (e) {",
    "      console.log('Error attaching resume:', e.message);",
    "    }",
    "",
    "    await page.waitForTimeout(3000);",
    "",
    "    try {",
    "      await page.evaluate(() => {",
    "        const closeBtn = document.querySelector(\"img[aria-label*='Save'], [aria-label*='Save'], .Ha\");",
    "        if (closeBtn) closeBtn.click();",
    "      });",
    "    } catch (e) {}",
    "    await page.waitForTimeout(1000);",
    "",
    "    results.push({ company: item.company, email: item.email, status: 'Drafted' });",
    "  }",
    "",
    "  return results;",
    "};"
]

with open("scratch/run_create_20_drafts.js", "w", encoding="utf-8") as out:
    out.write("\n".join(js_lines))

print("Created scratch/run_create_20_drafts.js successfully.")
